-- =============================================================================
-- Business schema upgrade: 0.2.15 -> 0.2.16 (PostgreSQL)
-- =============================================================================
--
-- Living upgrade path while 0.2.16 is unreleased. Apply to a database
-- installed at 0.2.15.
--
-- Fresh installs: make pgsqldb (pre + schema + procedures + post + Static).
-- Do not use this script for a greenfield install.
--
-- PRECONDITIONS
--   * Active SchemaVersion is Business 0.2.15 (stop IS NULL)
--   * Backup recommended for production
--
-- HOW TO RUN
--   psql -h <host> -U <user> -d <db> -v ON_ERROR_STOP=1 \
--     -f PostgreSQL/0.2.15-0.2.16.sql
--
-- The script is one transaction. A failed statement rolls the change back.
--
-- Version stamp stays commented until 0.2.16 is released.
--
-- =============================================================================

\set ON_ERROR_STOP on

BEGIN;

SET search_path TO business, public;

DO $$
BEGIN
 IF NOT EXISTS (
  SELECT true
  FROM schemaversion
  JOIN word AS schema ON schema.id = schemaversion.schema
  JOIN version ON version.id = schemaversion.version
  JOIN word AS major ON major.id = version.major
  JOIN word AS minor ON minor.id = version.minor
  JOIN word AS patch ON patch.id = version.patch
  WHERE schema.value = 'Business'
   AND major.value = '0'
   AND minor.value = '2'
   AND patch.value = '15'
   AND stop IS NULL
 ) THEN
  RAISE EXCEPTION 'Not Schema Version 0.2.15';
 END IF;
END $$;

CREATE TABLE EntryDescription (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entry integer NOT NULL,
 description integer NOT NULL,
 stop timestamp,
 created timestamp NOT NULL DEFAULT NOW(),
 CONSTRAINT entrydescription_entry
  FOREIGN KEY (entry) REFERENCES Entry (id) DEFERRABLE
);

CREATE UNIQUE INDEX entrydescription_entry_open
 ON EntryDescription (entry)
 WHERE stop IS NULL;

CREATE TABLE EntryReference (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entry integer NOT NULL,
 type integer,
 value varchar(80) NOT NULL,
 sequence smallint,
 stop timestamp,
 created timestamp NOT NULL DEFAULT NOW(),
 CONSTRAINT entryreference_entry
  FOREIGN KEY (entry) REFERENCES Entry (id) DEFERRABLE
);

CREATE UNIQUE INDEX entryreference_entry_type_open
 ON EntryReference (entry, type)
 WHERE stop IS NULL;

CREATE OR REPLACE VIEW EntryDescriptions AS
SELECT
 EntryDescription.id,
 EntryDescription.entry,
 I18NSentence.value AS description,
 EntryDescription.created
FROM EntryDescription
JOIN I18NSentence ON I18NSentence.id = EntryDescription.description
WHERE EntryDescription.stop IS NULL;

CREATE OR REPLACE VIEW EntryReferences AS
SELECT
 EntryReference.id,
 EntryReference.entry,
 COALESCE(RefIdent.value, RefWord.value) AS referenceType,
 EntryReference.value,
 EntryReference.sequence,
 EntryReference.created
FROM EntryReference
LEFT JOIN Word AS RefIdent ON RefIdent.id = EntryReference.type
 AND RefIdent.culture IS NULL
LEFT JOIN I18NWord AS RefWord ON RefWord.id = EntryReference.type
WHERE EntryReference.stop IS NULL;

-- One open sentence for an entry. A different sentence stops the open row.
CREATE OR REPLACE FUNCTION SetEntryDescription (
 inEntry integer,
 inDescription varchar
) RETURNS integer AS $$
DECLARE
 sentence_id integer;
 description_id integer;
BEGIN
 IF inEntry IS NULL OR inDescription IS NULL OR btrim(inDescription) = '' THEN
  RETURN NULL;
 END IF;

 sentence_id := GetSentence(inDescription);

 PERFORM pg_advisory_lock(inEntry);
 BEGIN
  UPDATE EntryDescription
  SET stop = NOW()
  WHERE entry = inEntry
   AND description <> sentence_id
   AND stop IS NULL;

  INSERT INTO EntryDescription (entry, description)
  SELECT inEntry, sentence_id
  WHERE NOT EXISTS (
   SELECT 1
   FROM EntryDescription
   WHERE entry = inEntry
    AND description = sentence_id
    AND stop IS NULL
  );

  SELECT id INTO description_id
  FROM EntryDescription
  WHERE entry = inEntry
   AND description = sentence_id
   AND stop IS NULL
  LIMIT 1;

  PERFORM pg_advisory_unlock(inEntry);
 EXCEPTION
  WHEN OTHERS THEN
   PERFORM pg_advisory_unlock(inEntry);
   RAISE;
 END;

 RETURN description_id;
END;
$$ LANGUAGE plpgsql;

-- One open reference of each type for an entry. value is the printed number.
-- A different value stops the open row of that type.
CREATE OR REPLACE FUNCTION SetEntryReference (
 inEntry integer,
 inType varchar,
 inValue varchar,
 inSequence smallint DEFAULT NULL
) RETURNS integer AS $$
DECLARE
 type_id integer;
 reference_id integer;
BEGIN
 IF inEntry IS NULL OR inType IS NULL OR btrim(inType) = ''
  OR inValue IS NULL OR btrim(inValue) = '' THEN
  RETURN NULL;
 END IF;

 type_id := GetIdentifier(inType);

 PERFORM pg_advisory_lock(inEntry);
 BEGIN
  UPDATE EntryReference
  SET stop = NOW()
  WHERE entry = inEntry
   AND type = type_id
   AND value <> inValue
   AND stop IS NULL;

  INSERT INTO EntryReference (entry, type, value, sequence)
  SELECT inEntry, type_id, inValue, inSequence
  WHERE NOT EXISTS (
   SELECT 1
   FROM EntryReference
   WHERE entry = inEntry
    AND type = type_id
    AND value = inValue
    AND stop IS NULL
  );

  SELECT id INTO reference_id
  FROM EntryReference
  WHERE entry = inEntry
   AND type = type_id
   AND value = inValue
   AND stop IS NULL
  LIMIT 1;

  IF inSequence IS NOT NULL THEN
   UPDATE EntryReference
   SET sequence = inSequence
   WHERE id = reference_id
    AND sequence IS DISTINCT FROM inSequence;
  END IF;

  PERFORM pg_advisory_unlock(inEntry);
 EXCEPTION
  WHEN OTHERS THEN
   PERFORM pg_advisory_unlock(inEntry);
   RAISE;
 END;

 RETURN reference_id;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION GetVersion (
 inMajor varchar,
 inMinor varchar,
 inPatch varchar
) RETURNS integer AS $$
DECLARE
 major_id integer;
 minor_id integer;
 patch_id integer;
 version_id integer;
BEGIN
 major_id := (SELECT GetIdentifier(inMajor));
 IF major_id IS NOT NULL THEN
  minor_id := (SELECT GetIdentifier(inMinor));
  patch_id := (SELECT GetIdentifier(inPatch));
  -- Match a version stored against any Word with the same text, including a culture word.
  SELECT id INTO version_id
  FROM Version
  WHERE name IS NULL
   AND major IN (SELECT id FROM Word WHERE UPPER(value) = UPPER(inMajor))
   AND ((inMinor IS NULL AND minor IS NULL) OR minor IN (SELECT id FROM Word WHERE UPPER(value) = UPPER(inMinor)))
   AND ((inPatch IS NULL AND patch IS NULL) OR patch IN (SELECT id FROM Word WHERE UPPER(value) = UPPER(inPatch)))
  ORDER BY id
  LIMIT 1;
  IF version_id IS NULL THEN
   -- Be sure to process any single version one at a time without the need of a transaction or locking Version table
   PERFORM pg_advisory_lock(major_id);
   BEGIN
   INSERT INTO Version (major, minor, patch) (
    SELECT major_id, minor_id, patch_id
    FROM Dual
    LEFT JOIN Version AS exists ON exists.name IS NULL
     AND exists.major IN (SELECT id FROM Word WHERE UPPER(value) = UPPER(inMajor))
     AND ((inMinor IS NULL AND exists.minor IS NULL) OR exists.minor IN (SELECT id FROM Word WHERE UPPER(value) = UPPER(inMinor)))
     AND ((inPatch IS NULL AND exists.patch IS NULL) OR exists.patch IN (SELECT id FROM Word WHERE UPPER(value) = UPPER(inPatch)))
    WHERE exists.id IS NULL
    LIMIT 1
   );
   PERFORM pg_advisory_unlock(major_id);
   EXCEPTION
    WHEN OTHERS THEN
     PERFORM pg_advisory_unlock(major_id);
     RAISE;
   END;
   SELECT id INTO version_id
   FROM Version
   WHERE name IS NULL
    AND major IN (SELECT id FROM Word WHERE UPPER(value) = UPPER(inMajor))
    AND ((inMinor IS NULL AND minor IS NULL) OR minor IN (SELECT id FROM Word WHERE UPPER(value) = UPPER(inMinor)))
    AND ((inPatch IS NULL AND patch IS NULL) OR patch IN (SELECT id FROM Word WHERE UPPER(value) = UPPER(inPatch)))
   ORDER BY id
   LIMIT 1;
  END IF;
 END IF;
 RETURN version_id;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION GetVersionName (
